const nodemailer = require('nodemailer');
const {
  getSignInTemplate,
  getLoanSubmittedTemplate,
  getLoanApprovedTemplate,
  getLoanRejectedTemplate,
  getLoanDisbursedTemplate,
  getRepaymentReceivedTemplate,
  getOverdueTemplate,
  getKycApprovedTemplate,
  getKycRejectedTemplate,
} = require('./emailTemplates');

/**
 * Robust Email Service supporting:
 * 1. Resend (via SMTP or direct API key)
 * 2. Brevo (via SMTP)
 * 3. Standard SMTP (Gmail, SendGrid, Mailtrap, custom host)
 * 4. Safe In-Memory / Test / Development Fallback when credentials are unconfigured or in automated test mode
 */
class EmailService {
  constructor() {
    this.name = 'email';
    this.transporter = null;
    this.providerType = 'none';
    this.isConfigured = false;
    this.sentEmailsHistory = []; // Useful for unit/integration testing
    this.init();
  }

  init() {
    // 1. Check if mock / test transport requested
    if (process.env.NODE_ENV === 'test' || process.env.EMAIL_MOCK_MODE === 'true') {
      this.providerType = 'mock';
      this.isConfigured = true;
      console.info('[EmailService] Initialized in MOCK/TEST mode — emails will be recorded in memory.');
      return;
    }

    // 2. Check for Resend (SMTP configuration)
    // Resend SMTP: host='smtp.resend.com', port=465 or 587, auth: { user: 'resend', pass: RESEND_API_KEY }
    if (process.env.RESEND_API_KEY) {
      try {
        this.transporter = nodemailer.createTransport({
          host: 'smtp.resend.com',
          port: 465,
          secure: true,
          auth: {
            user: 'resend',
            pass: process.env.RESEND_API_KEY.trim(),
          },
        });
        this.providerType = 'resend';
        this.isConfigured = true;
        console.info('[EmailService] Configured with Resend SMTP provider.');
        return;
      } catch (err) {
        console.error('[EmailService] Failed to initialize Resend transport:', err.message);
      }
    }

    // 3. Check for Brevo (SMTP configuration)
    // Brevo SMTP: host='smtp-relay.brevo.com' or 'smtp-relay.sendinblue.com', port=587, auth: { user: BREVO_USER, pass: BREVO_API_KEY }
    if (process.env.BREVO_API_KEY && process.env.BREVO_USER) {
      try {
        this.transporter = nodemailer.createTransport({
          host: process.env.BREVO_HOST || 'smtp-relay.brevo.com',
          port: Number(process.env.BREVO_PORT) || 587,
          secure: false,
          auth: {
            user: process.env.BREVO_USER.trim(),
            pass: process.env.BREVO_API_KEY.trim(),
          },
        });
        this.providerType = 'brevo';
        this.isConfigured = true;
        console.info('[EmailService] Configured with Brevo SMTP provider.');
        return;
      } catch (err) {
        console.error('[EmailService] Failed to initialize Brevo transport:', err.message);
      }
    }

    // 4. Check for Standard SMTP (Host, User, Pass)
    if (process.env.SMTP_HOST && process.env.SMTP_USER && process.env.SMTP_PASS) {
      try {
        const host = process.env.SMTP_HOST.trim();
        const port = Number(process.env.SMTP_PORT) || 587;
        const isSecure = process.env.SMTP_SECURE === 'true' || port === 465;
        let pass = process.env.SMTP_PASS.trim();
        
        // Strip embedded spaces often generated by Google App Passwords
        if (host.includes('gmail.com') || (process.env.SMTP_USER && process.env.SMTP_USER.includes('@gmail.com'))) {
          pass = pass.replace(/\s+/g, '');
        }

        const transportConfig = {
          host,
          port,
          secure: isSecure, // true for 465, false for 587 / STARTTLS
          auth: {
            user: process.env.SMTP_USER.trim(),
            pass,
          },
        };

        // Enforce STARTTLS for port 587
        if (!isSecure && port === 587) {
          transportConfig.requireTLS = true;
        }

        this.transporter = nodemailer.createTransport(transportConfig);
        this.providerType = 'smtp';
        this.isConfigured = true;
        console.info(`[EmailService] Configured with standard SMTP (${host}:${port}, secure=${isSecure}).`);
        return;
      } catch (err) {
        console.error('[EmailService] Failed to initialize SMTP transport:', this.redactSecrets(err.message));
      }
    }

    // 5. Fallback: Development Safe Log Transport
    this.providerType = 'dev_fallback';
    this.isConfigured = false;
    console.info('[EmailService] No external email provider credentials configured. Running in safe dev fallback mode.');
  }

  /**
   * Helper to redact sensitive credentials (passwords, API keys) from error logs and responses
   */
  redactSecrets(str) {
    if (!str || typeof str !== 'string') return str;
    let sanitized = str;
    if (process.env.SMTP_PASS) {
      const rawPass = process.env.SMTP_PASS.trim();
      const strippedPass = rawPass.replace(/\s+/g, '');
      sanitized = sanitized.split(rawPass).join('[REDACTED_PASS]');
      sanitized = sanitized.split(strippedPass).join('[REDACTED_PASS]');
    }
    if (process.env.RESEND_API_KEY) {
      sanitized = sanitized.split(process.env.RESEND_API_KEY.trim()).join('[REDACTED_KEY]');
    }
    if (process.env.BREVO_API_KEY) {
      sanitized = sanitized.split(process.env.BREVO_API_KEY.trim()).join('[REDACTED_KEY]');
    }
    return sanitized;
  }

  /**
   * Verify SMTP connection using transporter.verify() safely
   */
  async verifyConnection() {
    if (!this.transporter || !this.isConfigured) {
      return { success: false, reason: 'Email transporter is not configured or initialized' };
    }
    try {
      await this.transporter.verify();
      console.info(`[EmailService] SMTP connection verified successfully (${this.providerType}).`);
      return { success: true, provider: this.providerType };
    } catch (err) {
      const safeReason = this.redactSecrets(err.message);
      console.error(`[EmailService] SMTP connection verification failed: ${safeReason}`);
      return { success: false, reason: safeReason };
    }
  }

  getSender() {
    if (process.env.EMAIL_FROM) {
      return process.env.EMAIL_FROM;
    }
    if (process.env.SMTP_USER) {
      return `"FarmSphere FPO" <${process.env.SMTP_USER.trim()}>`;
    }
    return process.env.RESEND_FROM || '"FarmSphere FPO" <notifications@farmsphere.org>';
  }

  /**
   * Core send method
   */
  async sendMail({ to, subject, html, text }) {
    if (!to) {
      return { delivered: false, reason: 'Recipient email address missing' };
    }

    const emailRecord = {
      to,
      subject,
      text,
      html,
      from: this.getSender(),
      timestamp: new Date(),
    };

    // Store in history (last 50 emails) for debugging/testing
    this.sentEmailsHistory.unshift(emailRecord);
    if (this.sentEmailsHistory.length > 50) {
      this.sentEmailsHistory.pop();
    }

    // Mock Mode
    if (this.providerType === 'mock') {
      return {
        delivered: true,
        provider: 'mock',
        messageId: `mock_${Date.now()}_${Math.random().toString(36).substring(7)}`,
      };
    }

    // Real transport
    if (this.transporter && this.isConfigured) {
      try {
        const info = await this.transporter.sendMail({
          from: this.getSender(),
          to,
          subject,
          text,
          html,
        });
        return {
          delivered: true,
          provider: this.providerType,
          messageId: info.messageId,
        };
      } catch (err) {
        const safeReason = this.redactSecrets(err.message);
        console.error(`[EmailService] ${this.providerType} delivery failed:`, safeReason);
        return {
          delivered: false,
          provider: this.providerType,
          reason: safeReason,
        };
      }
    }

    // Dev Fallback Mode (Console logging without throwing)
    console.info(`[EmailService DevFallback] Simulated email dispatch to ${to}: "${subject}"`);
    return {
      delivered: false,
      provider: 'dev_fallback',
      reason: 'No live provider credentials configured (RESEND_API_KEY or SMTP_HOST missing)',
    };
  }

  /**
   * Adapter for NotificationService provider interface:
   * async send(payload) where payload = { userId, type, title, body, metadata, ... }
   */
  async send(payload) {
    try {
      const User = require('../models/User');

      let email = payload?.email;
      let name = payload?.name;

      if (!email && payload?.userId) {
        const recipient = await User.findById(payload.userId).select('name email role');
        if (recipient) {
          email = recipient.email;
          name = recipient.name;
        }
      }

      if (!email) {
        return { provider: this.name, delivered: false, reason: 'no email address registered for user' };
      }

      const type = payload?.type;
      const metadata = payload?.metadata || {};
      const appUrl = process.env.APP_URL || 'http://localhost:5173';

      let templateResult = null;

      switch (type) {
        case 'USER_SIGN_IN':
          templateResult = getSignInTemplate({
            name,
            email,
            loginTime: metadata.loginTime || new Date(),
            ipAddress: metadata.ipAddress,
            userAgent: metadata.userAgent,
            appUrl,
          });
          break;

        case 'LOAN_SUBMITTED':
          templateResult = getLoanSubmittedTemplate({
            name,
            loanId: metadata.loanId || payload.entityId,
            schemeName: metadata.schemeName,
            loanAmount: metadata.amount,
            purpose: metadata.purpose,
            tenureMonths: metadata.tenureMonths,
            appUrl,
          });
          break;

        case 'LOAN_APPROVED':
          templateResult = getLoanApprovedTemplate({
            name,
            loanId: metadata.loanId || payload.entityId,
            schemeName: metadata.schemeName,
            approvedAmount: metadata.amount,
            interestRate: metadata.interestRate,
            tenureMonths: metadata.tenureMonths,
            appUrl,
          });
          break;

        case 'LOAN_REJECTED':
          templateResult = getLoanRejectedTemplate({
            name,
            loanId: metadata.loanId || payload.entityId,
            schemeName: metadata.schemeName,
            reason: metadata.reason || payload.body,
            appUrl,
          });
          break;

        case 'LOAN_DISBURSED':
          templateResult = getLoanDisbursedTemplate({
            name,
            loanId: metadata.loanId || payload.entityId,
            schemeName: metadata.schemeName,
            disbursedAmount: metadata.amount,
            disbursedDate: metadata.disbursedDate || new Date(),
            dueDate: metadata.dueDate,
            firstEmiAmount: metadata.firstEmiAmount,
            appUrl,
          });
          break;

        case 'PAYMENT_RECORDED':
          templateResult = getRepaymentReceivedTemplate({
            name,
            loanId: metadata.loanId,
            amount: metadata.amount,
            remainingBalance: metadata.remainingBalance,
            paymentDate: metadata.paymentDate || new Date(),
            paymentMethod: metadata.paymentMethod,
            appUrl,
          });
          break;

        case 'EMI_OVERDUE':
          templateResult = getOverdueTemplate({
            name,
            loanId: metadata.loanId,
            amount: metadata.amount,
            dueDate: metadata.dueDate,
            appUrl,
          });
          break;

        case 'KYC_APPROVED':
          templateResult = getKycApprovedTemplate({
            name,
            reviewedAt: metadata.reviewedAt || new Date(),
            appUrl,
          });
          break;

        case 'KYC_REJECTED':
          templateResult = getKycRejectedTemplate({
            name,
            reason: metadata.rejectionReason || metadata.reason,
            appUrl,
          });
          break;

        default:
          // Generic notification fallback
          templateResult = {
            subject: `FarmSphere: ${payload.title || 'Notification'}`,
            text: `${payload.title}\n\n${payload.body}`,
            html: `<div style="font-family:sans-serif;padding:20px;line-height:1.6;"><h2>${payload.title}</h2><p>${payload.body}</p></div>`,
          };
          break;
      }

      if (!templateResult) {
        return { provider: this.name, delivered: false, reason: 'Template generation failed' };
      }

      const result = await this.sendMail({
        to: email,
        subject: templateResult.subject,
        html: templateResult.html,
        text: templateResult.text,
      });

      return {
        provider: this.name,
        providerUsed: result.provider,
        delivered: result.delivered,
        messageId: result.messageId,
        reason: result.reason,
      };
    } catch (err) {
      console.error('[EmailService Provider] Error:', err.message);
      return { provider: this.name, delivered: false, reason: err.message };
    }
  }
}

let emailSingleton = null;

const getEmailService = () => {
  if (!emailSingleton) {
    emailSingleton = new EmailService();
  }
  return emailSingleton;
};

module.exports = {
  EmailService,
  getEmailService,
};
